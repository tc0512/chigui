import sys
import os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import turtle
import graphicssystem as gs

turtle.setup(720, 720)
turtle.setworldcoordinates(-4, -4, 4, 4)
A = gs.Point(0, 0)
A.plot(label="A")
c1 = gs.Circle(A, 1)
c1.plot(speed=0)
B = gs.Point(-1, 0)
C = gs.Point(1, 0)
s1 = gs.Seg(B, C)
s1.plot()
B.plot(label="B")
C.plot(label="C")
c2 = gs.Circle(C, A.distance(C))
c2.plot(speed=0)
p1, p2 = c1.intersection(c2)
D = gs.Point(p2.x, p2.y)
D.plot(label="D")
c3 = gs.Circle(D, A.distance(D))
c3.plot(speed=0)
p1, p2 = c3.intersection(c1)
E = gs.Point(p2.x, p2.y)
E.plot(label="E")
r1 = gs.Ray(A, D)
p1, p2 = r1.intersection(c3)
F = gs.Point(p2.x, p2.y)
s2 = gs.Seg(A, F)
s2.plot()
F.plot(label="F")
s3 = gs.Seg(C, F)
s3.plot()
p = s3.intersection(c2)[0]
G = gs.Point(p.x, p.y)
G.plot(label="G")
c4 = gs.Circle(G, C.distance(G))
c4.plot(speed=0)
p1, p2 = c4.intersection(c3)
H = gs.Point(p2.x, p2.y)
H.plot(label="H")
c5 = gs.Circle(E, E.distance(H))
c5.plot(speed=0)
p = c5.intersection(s1)[0]
J = gs.Point(p.x, p.y) # J((√5-1)/2,0)
J.plot(label="J", c="gold")
c6 = gs.Circle(J, A.distance(J))
c6.plot(speed=0)
p1, p2 = c6.intersection(c1)
L = gs.Point(p2.x, p2.y)
L.plot(label="L")
K = gs.Point(p1.x, p1.y)
K.plot(label="K")
c7 = gs.Circle(C, K.distance(L))
c7.plot(speed=0)
p1, p2 = c7.intersection(c1)
N = gs.Point(p2.x, p2.y)
N.plot(label="N")
M = gs.Point(p1.x, p1.y)
M.plot(label="M")
c8 = gs.Circle(M, K.distance(M))
c8.plot(speed=0)
p1, p2 = c8.intersection(c1)
R = gs.Point(p2.x, p2.y)
R.plot(label="R")
c9 = gs.Circle(N, N.distance(L))
c9.plot(speed=0)
p1, p2 = c9.intersection(c1)
S = gs.Point(p1.x, p1.y)
S.plot(label="S")
c10 = gs.Circle(B, S.distance(N))
c10.plot(speed=0)
p1, p2 = c10.intersection(c1)
Q = gs.Point(p2.x, p2.y)
Q.plot(label="Q")
P = gs.Point(p1.x, p1.y)
P.plot(label="P")
points = [C, L, N, S, Q, B, P, R, M, K, C]
for i in range(10):
    gs.Seg(points[i], points[i+1]).plot(c="red")
turtle.done()
