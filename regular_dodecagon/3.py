import sys
import os

from sympy import im
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import turtle
import sympy as sp
import graphicssystem as gs
turtle.setup(720, 540)
turtle.setworldcoordinates(-4, -3, 4, 3)
A = gs.Point(0, 0)
A.plot(label="A")
c1 = gs.Circle(A, 1)
c1.plot()
B = gs.Point(sp.sqrt(3)/2, sp.Rational(1, 2))
B.plot(label="B")
c2 = gs.Circle(B, A.distance(B))
c2.plot()
p1, p2 = c2.intersection(c1)
D = gs.Point(p1.x, p1.y)
D.plot(label="D")
C = gs.Point(p2.x, p2.y)
C.plot(label="C")
c3 = gs.Circle(C, A.distance(C))
c3.plot()
p1, p2 = c3.intersection(c1)
E = gs.Point(p1.x, p1.y)
E.plot(label="E")
p1, p2 = c2.intersection(c3)
F = gs.Point(p2.x, p2.y)
F.plot(label="F")
r1 = gs.Ray(F, A)
p1, p2 = r1.intersection(c1)
H = gs.Point(p1.x, p1.y)
s1 = gs.Seg(F, H)
s1.plot()
H.plot(label="H")
G = gs.Point(p2.x, p2.y)
G.plot(label="G")
c4 = gs.Circle(G, A.distance(G))
c4.plot()
c5 = gs.Circle(H, A.distance(H))
c5.plot()
r2 = gs.Ray(C, A)
p1, p2 = r2.intersection(c1)
I = gs.Point(p1.x, p1.y)
s2 = gs.Seg(C, I)
s2.plot()
I.plot(label="I")
r3 = gs.Ray(B, A)
p1, p2 = r3.intersection(c1)
J = gs.Point(p1.x, p1.y)
s3 = gs.Seg(B, J)
s3.plot()
J.plot(label="J")
p1, p2 = c4.intersection(c1)
K, L = gs.Point(p1.x, p1.y), gs.Point(p2.x, p2.y)
K.plot(label="K")
L.plot(label="L")
p1, p2 = c5.intersection(c1)
M, N = gs.Point(p1.x, p1.y), gs.Point(p2.x, p2.y)
M.plot(label="M")
N.plot(label="N")
points = [B, G, C, K, E, M, J, H, I, N, D, L, B]
for i in range(12):
    gs.Seg(points[i], points[i+1]).plot(c="red")
turtle.done()
