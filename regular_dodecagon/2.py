import sys
import os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import turtle
import graphicssystem as gs
turtle.setup(720, 540)
turtle.setworldcoordinates(-4, -3, 4, 3)
A = gs.Point(0, 0)
A.plot(label="A")
c1 = gs.Circle(A, 1)
c1.plot()
B = gs.Point(-1, 0)
C = gs.Point(1, 0)
s1 = gs.Seg(B, C)
s1.plot()
B.plot(label="B")
C.plot(label="C")
c2 = gs.Circle(B, B.distance(C))
c2.plot()
c3 = gs.Circle(C, B.distance(C))
c3.plot()
p1, p2 = c2.intersection(c3)
D = gs.Point(p1.x, p1.y)
D.plot(label="D")
r1 = gs.Ray(D, A)
p1, p2 = r1.intersection(c1)
F = gs.Point(p1.x, p1.y)
s2 = gs.Seg(D, F)
s2.plot()
E = gs.Point(p2.x, p2.y)
E.plot(label="E")
F.plot(label="F")
c4 = gs.Circle(C, A.distance(C))
c4.plot()
c5 = gs.Circle(E, A.distance(E))
c5.plot()
c6 = gs.Circle(B, A.distance(B))
c6.plot()
c7 = gs.Circle(F, A.distance(F))
c7.plot()
p1, p2 = c4.intersection(c1)
G, H = gs.Point(p1.x, p1.y), gs.Point(p2.x, p2.y)
G.plot(label="G")
H.plot(label="H")
p1, p2 = c5.intersection(c1)
I, J = gs.Point(p1.x, p1.y), gs.Point(p2.x, p2.y)
I.plot(label="I")
J.plot(label="J")
p1, p2 = c6.intersection(c1)
K, L = gs.Point(p1.x, p1.y), gs.Point(p2.x, p2.y)
K.plot(label="K")
L.plot(label="L")
p1, p2 = c7.intersection(c1)
M, N = gs.Point(p1.x, p1.y), gs.Point(p2.x, p2.y)
M.plot(label="M")
N.plot(label="N")
points = [B, I, L, E, H, J, C, N, G, F, K, M, B]
for i in range(12):
    gs.Seg(points[i], points[i+1]).plot(c="red")
turtle.done()
