import sys
import os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import turtle
import graphicssystem as gs
turtle.setup(720, 720)
turtle.setworldcoordinates(-4, -4, 4, 4)
O = gs.Point(0, 0)
O.plot(label="O")
c1 = gs.Circle(O, 1)
c1.plot()
B = gs.Point(0, -1)
D = gs.Point(0, 1)
s1 = gs.Seg(B, D)
s1.plot()
B.plot(label="B")
D.plot(label="D")
c2 = gs.Circle(D, B.distance(D))
c2.plot()
c3 = gs.Circle(B, B.distance(D))
c3.plot()
p1, p2 = c2.intersection(c3)
E = gs.Point(p1.x, p1.y)
E.plot(label="E")
r1 = gs.Ray(E, O)
p1, p2 = r1.intersection(c1)
A = gs.Point(p1.x, p1.y)
s2 = gs.Seg(E, A)
s2.plot()
C = gs.Point(p2.x, p2.y)
A.plot(label="A")
C.plot(label="C")
c4 = gs.Circle(A, A.distance(O))
c4.plot()
p1, p2 = c4.intersection(c1)
F = gs.Point(p2.x, p2.y)
F.plot(label="F")
s3 = gs.Seg(F, O)
s3.plot(c="yellow")
s4 = gs.Seg(D, O)
s4.plot(c="yellow")
print("∠α=∠DOF=30")
turtle.done()
